/** Small physical lettering. Adjacent pixels form one strip, not individual cubes. */
export function lettering(k:Kit,slot:string,text:string,x:number,y:number,z:number,cell=.009):void{
  let cursor=x;
  for(const char of text){const glyph=FONT[char];if(glyph)for(let row=0;row<7;row++){
    const bits=glyph[row]!;for(let col=0;col<5;){if(bits[col]!=='1'){col++;continue;}const start=col;while(col<5&&bits[col]==='1')col++;
      k.box(slot,[cursor+start*cell,y+(6-row)*cell,z],[cell*(col-start),cell,.0008]);}
  }cursor+=cell*6;}
}
