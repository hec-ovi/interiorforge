function fit(candidate = room) {
  return fitBathroomRecipe(candidate, sizes, createRng('bath-bound-proof'), footprint =>
    roomCoversRect(candidate, footprint, .05) && roomCoversRect(inside, footprint)
      && blocked.every(keepout => !overlaps(footprint, keepout, .15)),
  operation => roomCoversRect(candidate, operation, BATHROOM_WALL_CLEARANCE) && roomCoversRect(inside, operation));
}

/** Exact scalar feasibility intervals for a fixed-size wall fitting. An overlapping
 * across-wall keepout removes an OPEN interval of along-wall positions; boundaries
 * remain legal. This analysis has no quarter-grid sampling and no search limit. */
function intervals(edge: 'u0' | 'u1' | 'v0' | 'v1', width: number, depth: number, keepouts: UvRect[]) {
  const horizontal = edge.startsWith('v'), along = horizontal ? 'u' : 'v', across = horizontal ? 'v' : 'u';
  const length = horizontal ? 'lu' : 'lv', thickness = horizontal ? 'lv' : 'lu';
  const r = room.rect, near = r[across] + .1, far = r[across] + r[thickness] - .1;
  const crossLow = edge.endsWith('0') ? near : far - depth, crossHigh = crossLow + depth;
  let ranges: [number, number][] = [[r[along] + .1, r[along] + r[length] - width - .1]];
  for (const obstacle of keepouts) {
    if (crossLow >= obstacle[across] + obstacle[thickness] + .15 - 1e-8
      || crossHigh + .15 <= obstacle[across] + 1e-8) continue;
    const low = obstacle[along] - width - .15, high = obstacle[along] + obstacle[length] + .15;
    ranges = ranges.flatMap(([a,b]) => {
      if (high <= a || low >= b) return [[a,b] as [number,number]];
      return [...(low >= a ? [[a,Math.min(b,low)] as [number,number]] : []),
        ...(high <= b ? [[Math.max(a,high),b] as [number,number]] : [])];
    });
  }
  return ranges;
}

it('proves the existing 3.5m room cannot fit even the mandatory vanity or shower alone', () => {
  const lastVanityInterval = intervals('v0', 2.2, .6, doors);
  expect(lastVanityInterval).toHaveLength(1);
  expect(lastVanityInterval[0]![0]).toBeCloseTo(105.15, 8);
  expect(lastVanityInterval[0]![1]).toBeCloseTo(105.2, 8);
  // This actual circulation box closes the only remaining 5cm offset interval.
  expect(intervals('v0', 2.2, .6, [...doors, circulation[84]!])).toEqual([]);
  for (const edge of ['u0','u1','v0','v1'] as const) {
    expect(intervals(edge, 2.2, .6, blocked), `vanity ${edge}`).toEqual([]);
    expect(intervals(edge, 1.3, 1.1, blocked), `shower ${edge}`).toEqual([]);
  }
  expect(fit()).toBeNull();
});

it('retains full fixtures and every original approach in a sufficient 4m by 4.5m allocation', () => {
  // Allocation control only: production planning must actually allocate the extra
  // floor and update adjacent rooms. The fitter does not silently grow a bathroom.
  const rect = { u:104, v:44.5, lu:4, lv:4.5 };
  const grown: PlanRoom = { ...room, rect, polygon: uvRectCorners(rect) };
  const result = fit(grown);
  expect(result?.map(item => item.kind).sort()).toEqual(['shower','sink','toilet']);
  for (const item of result!) {
    const footprint = item.footprint, canonical = sizes[item.kind];
    const swapped = item.rotationDeg % 180 !== 0;
    expect(footprint.lu).toBe(canonical[swapped ? 1 : 0]);
    expect(footprint.lv).toBe(canonical[swapped ? 0 : 1]);
    expect(blocked.some(keepout => overlaps(footprint, keepout, .15)), item.kind).toBe(false);
    expect(roomCoversRect(grown, item.operation, BATHROOM_WALL_CLEARANCE), item.kind).toBe(true);
    for (const other of result!) if (other !== item) {
      expect(overlaps(footprint, other.footprint, .15), `${item.kind}/${other.kind}`).toBe(false);
      expect(overlaps(footprint, other.operation), `${item.kind}/${other.kind} approach`).toBe(false);
    }
  }
});
